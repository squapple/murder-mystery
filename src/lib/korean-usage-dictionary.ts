// 가깝다 — 그래서 국어사전처럼 뜻과 활용법까지 같이 적어, 모델이 그 표현을 맥락과
// 함께 참고할 수 있게 한다(단순 대응 쌍보다 일반화에 도움이 될지는 아직 검증 전 —
// 다음에 실측할 것).
//
// 운영 방식: 로그에서 모델이 스스로 못 고친 오류를 발견하면 이 배열에 항목을 추가한다.
// 항목이 쌓이면 주기적으로 훑어보면서 "같은 유형"으로 묶이는 게 보이면(예: 이중부정류가
// 여러 개 쌓이면) 개별 항목 나열 대신 quality-check.ts의 (a)~(e) 같은 일반 규칙 한 줄로
// 승격시키고, 승격된 항목은 이 목록에서 뺀다 — 사전은 "아직 규칙으로 못 뽑아낸, 모델이
// 개별적으로 계속 틀리는 표현"만 담아 계속 slim하게 유지한다.
export interface DictionaryEntry {
  /** 오류가 있는 실제 원문 표현 */
  wrong: string;
  /** 올바른 표현. 후보가 여럿이면 배열에 다 적는다. */
  correct: string[];
  /** 어떤 유형의 결함인지 짧은 분류 */
  note: string;
  /** 이 표현(또는 정답 표현)이 실제로 무슨 뜻인지 — 특히 관용구처럼 글자 그대로
   * 해석하면 안 되는 경우에 중요하다. */
  meaning: string;
  /** 문법 구조·활용 설명(선택) — 왜 틀렸는지 알아야 비슷한 다른 문장에도 적용할
   * 여지가 생긴다는 가설로 추가했다. 효과는 아직 미검증. */
  usage?: string;
}

