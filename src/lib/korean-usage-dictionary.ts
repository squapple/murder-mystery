/** 교정 지시문에 그대로 붙일 수 있는 형태로 렌더링한다 — 뜻·활용법까지 포함한다. */
export function renderKoreanUsageDictionary(): string {
  return KOREAN_USAGE_DICTIONARY.map((e) => {
    const parts = [
      `"${e.wrong}"`,
      `(${e.note}`,
      `뜻: ${e.meaning}`,
      e.usage ? `활용: ${e.usage}` : null,
      `올바르게는 ${e.correct.map((c) => `"${c}"`).join("/")})`,
    ].filter(Boolean);
    return parts.join(", ");
  }).join("; ");
}
