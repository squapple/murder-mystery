// 깨진 관용구 등)은 실전 로그에서 발견되는 구체적 사례를 예시로 박아넣어야 모델이
// 잡아낸다(Phase 67에서 확인). 새 사례를 발견할 때마다 거대한 프롬프트 문자열을
// 직접 헤집지 않고 이 배열에 항목만 추가하면 되도록 분리했다.
export interface CorrectionExample {
  /** 오류가 있는 실제 원문 표현 */
  wrong: string;
  /** 올바른 표현. 후보가 여럿이면 배열에 다 적는다(예: "갔겠어요"/"갔겠습니까"). */
  correct: string[];
  /** 어떤 유형의 결함인지 짧은 설명 */
  note: string;
}

