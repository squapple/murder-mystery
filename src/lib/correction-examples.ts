/** 교정 지시문의 "예: ..." 절에 그대로 붙일 수 있는 형태로 렌더링한다. */
export function renderCorrectionExamples(): string {
  return CORRECTION_EXAMPLES.map(
    (e) => `"${e.wrong}"(${e.note}, 올바르게는 ${e.correct.map((c) => `"${c}"`).join("/")})`
  ).join(", ");
}
